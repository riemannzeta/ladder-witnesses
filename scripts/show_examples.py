"""Write docs/examples.md: a few concrete episodes per experiment with their exact oracle values."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import torch

from witnesses.tasks import dag_utils as du
from witnesses.tasks.e1_simpson import EST_NAMES, EST_TABLE, PERMS, E1Simpson, cxy_index
from witnesses.tasks.e2_dags import E2Dags, answers_torch
from witnesses.tasks.e3_twin import E3Twin
from witnesses.tasks.e4_identify import E4Identify

ROOT = Path(__file__).resolve().parents[1]
CPU = torch.device("cpu")
L = ["A", "B", "C"]


def e1(lines: list[str]) -> None:
    torch.manual_seed(5)
    t = E1Simpson(alpha=0.3, n_samples=128)
    ep = {k: v.cpu() for k, v in t._episodes(4, CPU).items()}
    orc = t.oracle(ep)["all"][:, -1]  # [B, 3, 2] at N = 128
    lines += ["## E1: Simpson pair over six orderings", "",
              "Same 128 samples; only the causal-ordering token changes the right answer.", ""]
    for b in range(2):
        x, y = int(ep["x"][b]), int(ep["y"][b])
        cnt = np.bincount(ep["cells"][b].numpy(), minlength=8)
        lines.append(f"**Episode {b}:** treatment X={L[x]}, outcome Y={L[y]}. Cell counts (A,B,C)→n: "
                     + ", ".join(f"{(c >> 2) & 1}{(c >> 1) & 1}{c & 1}:{n}" for c, n in enumerate(cnt)))
        lines.append("")
        lines.append("| ordering | estimand | P(Y=1|do(X=1)) | P(Y=1|do(X=0)) |")
        lines.append("|---|---|---|---|")
        for p, perm in enumerate(PERMS):
            e = EST_TABLE[p, x, y]
            lines.append(f"| {'→'.join(L[i] for i in perm)} | {EST_NAMES[e]} | {orc[b, e, 1]:.3f} | {orc[b, e, 0]:.3f} |")
        mix = (orc[b] * np.array([1 / 6, 2 / 6, 3 / 6])[:, None]).sum(0)
        lines += [f"| *graph-blind Bayes* | mixture | {mix[1]:.3f} | {mix[0]:.3f} |", ""]


def e2(lines: list[str]) -> None:
    torch.manual_seed(3)
    t = E2Dags(mode="cpt", fold=0)
    st, q = t._draw(400, CPU, t.train_topos)
    do_a, cond_a = answers_torch(st["pa"], st["theta"].double(), q)
    idx = [i for i in range(400) if not q["is_cond"][i] and abs(do_a[i] - cond_a[i]) > 0.1][:2]
    lines += ["## E2-0: given the graph and CPTs, intervene vs condition", ""]
    for b in idx:
        pa = tuple(int(v) for v in st["pa"][b])
        perm = st["perm"][b].tolist()
        edges = ", ".join(f"V{perm[p]}→V{perm[i]}" for i in range(4) for p in du.parents_of(pa[i]))
        A, T = int(q["A"][b]), int(q["T"][b])
        sec = int(q["B"][b])
        lines.append(f"- graph: {edges}; query: P(V{perm[T]}=1 | do(V{perm[A]}={int(q['va'][b])})"
                     + (f", inert do(V{perm[sec]}={int(q['vb'][b])})" if sec >= 0 else "")
                     + f"): **do = {do_a[b]:.3f}** vs conditioning = {cond_a[b]:.3f}")
    lines.append("")


def e3(lines: list[str]) -> None:
    torch.manual_seed(2)
    t = E3Twin()
    ep = {k: v.cpu() for k, v in t._episodes(64, CPU, torch.tensor([-1.0, 0.5] * 32)).items()}
    orc = t.oracle(ep)
    lines += ["## E3: residual twin", "", "| ρ | x* | y* | x′ | crossing | oracle CF (32 pairs) | L2 answer m·x′ |",
              "|---|---|---|---|---|---|---|"]
    for b in [i for i in range(64) if ep["cross"][i]][:3] + [i for i in range(64) if not ep["cross"][i]][:1]:
        lines.append(f"| {ep['rho'][b]:+.1f} | {ep['xs'][b]:+.2f} | {ep['ys'][b]:+.2f} | {ep['xp'][b]:+.2f} | "
                     f"{bool(ep['cross'][b])} | {orc['cf'][b, -1]:+.3f} | {orc['l2'][b, -1]:+.3f} |")
    lines.append("")


def e4(lines: list[str]) -> None:
    t = E4Identify(alpha=0.5, n_samples=256, mc=4096)
    rng = np.random.default_rng(0)
    lines += ["## E4: posterior sd of P(Y=1|do(X=1)) as samples accumulate (exact oracle, median of 200 episodes)", "",
              "| cell | k=16 | k=64 | k=256 |", "|---|---|---|---|"]
    for vis, g in (("obs", "conf"), ("hid", "med"), ("hid", "conf")):
        torch.manual_seed(1)
        ep = t._episodes(200, CPU)
        cells = ep["cells"].numpy()
        row = []
        for k in (16, 64, 256):
            _, sd = t._posterior_hist(cells, vis == "hid", g == "conf", k, rng)
            row.append(f"{np.median(sd):.3f}")
        lines.append(f"| {vis.upper()}-{g.upper()} | " + " | ".join(row) + " |")
    lines.append("")


def main() -> None:
    lines = ["# Example episodes with exact oracle values", "",
             "Generated by `scripts/show_examples.py` from the task generators and oracles.", ""]
    for f in (e1, e2, e3, e4):
        f(lines)
    out = ROOT / "docs" / "examples.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
